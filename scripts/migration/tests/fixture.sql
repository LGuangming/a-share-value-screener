CREATE SCHEMA research;
CREATE TABLE public.stocks (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text UNIQUE NOT NULL);
CREATE TABLE research.quotes (stock_id bigint REFERENCES public.stocks(id), day date NOT NULL, close numeric(18,4), details jsonb, observed timestamptz, raw bytea, PRIMARY KEY(stock_id,day));
CREATE INDEX quotes_day_idx ON research.quotes(day);
CREATE TABLE research.unkeyed (payload text);
CREATE TABLE research.events (day date, payload text) PARTITION BY RANGE(day);
CREATE TABLE research.events_2026 PARTITION OF research.events FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
CREATE VIEW research.latest AS SELECT stock_id, max(day) AS day FROM research.quotes GROUP BY stock_id;
CREATE FUNCTION research.twice(x integer) RETURNS integer LANGUAGE sql IMMUTABLE AS 'SELECT x * 2';
